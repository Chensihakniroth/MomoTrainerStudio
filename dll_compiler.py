"""
dll_compiler.py — DLL compiler for MomoTrainer Studio
made by Momo aka Steav Beoung Salang

Generates and compiles injectable DLLs from cheat table entries.

Features:
  - DllMain entry point with background thread
  - Value freeze (continuous write)
  - Value set (one-shot write)
  - Nudge (increment/decrement)
  - Hotkey support (toggle features at runtime)
  - Clean unload (close the DLL via deinject)

Usage:
    compiler = DLLCompiler()
    compiler.generate(features, "output.dll")
    compiler.compile("output.dll", g++_path="g++")
"""

import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import List, Dict, Optional


# ============================================================
# DLL Template — the C++ source template
# ============================================================

DLL_TEMPLATE = r"""
// ============================================================
//  {dll_name}
//  Generated by MomoTrainer Studio — {timestamp}
//  Injectable game cheat DLL
// ============================================================

#include <windows.h>
#include <cstdint>
#include <thread>
#include <vector>
#include <atomic>

// ============================================================
//  Feature configuration
// ============================================================

// ============================================================
//  Memory utilities
// ============================================================
template<typename T>
bool write_memory(uintptr_t address, T value) {{
    HANDLE hProcess = GetCurrentProcess();
    SIZE_T written;
    return WriteProcessMemory(hProcess, (LPVOID)address, &value, sizeof(T), &written) != 0;
}}

template<typename T>
T read_memory(uintptr_t address) {{
    T value = {{}};
    HANDLE hProcess = GetCurrentProcess();
    SIZE_T read;
    ReadProcessMemory(hProcess, (LPVOID)address, &value, sizeof(T), &read);
    return value;
}}

// ============================================================
//  Feature structure
// ============================================================
struct CheatFeature {{
    const char* name;
    uintptr_t   address;
    uint32_t    value_type;   // 0=int32, 1=uint32, 2=float, 3=int64, 4=double
    int32_t     int32_val;
    int64_t     int64_val;
    float       float_val;
    double      double_val;
    int32_t     nudge_amount;
    int32_t     mode;         // 0=freeze, 1=set, 2=nudge
    int32_t     hotkey;       // VK code, 0=none
    bool        enabled;
    bool        toggle;       // for hotkey toggle
}};

// ============================================================
//  Global state
// ============================================================
std::atomic<bool> g_running(true);
std::vector<CheatFeature> g_features;
HANDLE g_thread = NULL;

// ============================================================
//  Cheat thread — runs in background
// ============================================================
DWORD WINAPI cheat_thread(LPVOID) {{
    while (g_running) {{
        for (auto& f : g_features) {{
            if (!f.enabled) continue;

            if (f.mode == 0) {{
                // Freeze: continuously write value
                switch (f.value_type) {{
                    case 0: write_memory<int32_t>(f.address, f.int32_val); break;
                    case 1: write_memory<uint32_t>(f.address, (uint32_t)f.int32_val); break;
                    case 2: write_memory<float>(f.address, f.float_val); break;
                    case 3: write_memory<int64_t>(f.address, f.int64_val); break;
                    case 4: write_memory<double>(f.address, f.double_val); break;
                }}
            }} else if (f.mode == 1) {{
                // Set: write once
                switch (f.value_type) {{
                    case 0: write_memory<int32_t>(f.address, f.int32_val); break;
                    case 1: write_memory<uint32_t>(f.address, (uint32_t)f.int32_val); break;
                    case 2: write_memory<float>(f.address, f.float_val); break;
                    case 3: write_memory<int64_t>(f.address, f.int64_val); break;
                    case 4: write_memory<double>(f.address, f.double_val); break;
                }}
                f.enabled = false;  // one-shot
            }} else if (f.mode == 2) {{
                // Nudge: add amount to current value
                switch (f.value_type) {{
                    case 0: {{
                        int32_t cur = read_memory<int32_t>(f.address);
                        write_memory<int32_t>(f.address, cur + f.nudge_amount);
                        break;
                    }}
                    case 1: {{
                        uint32_t cur = read_memory<uint32_t>(f.address);
                        write_memory<uint32_t>(f.address, cur + f.nudge_amount);
                        break;
                    }}
                    case 2: {{
                        float cur = read_memory<float>(f.address);
                        write_memory<float>(f.address, cur + (float)f.nudge_amount);
                        break;
                    }}
                }}
                f.enabled = false;  // one-shot
            }}

            // Hotkey toggle check
            if (f.hotkey != 0 && (GetAsyncKeyState(f.hotkey) & 1)) {{
                f.toggle = !f.toggle;
                f.enabled = f.toggle;
                Sleep(200);  // debounce
            }}
        }}
        Sleep(10);  // 10ms cycle — ~100Hz
    }}
    return 0;
}}

// ============================================================
//  DLL Entry Point
// ============================================================
BOOL APIENTRY DllMain(HMODULE hModule, DWORD reason, LPVOID reserved) {{
    switch (reason) {{
        case DLL_PROCESS_ATTACH:
            DisableThreadLibraryCalls(hModule);
            g_running = true;
            // Initialize features
            g_features = {{
{feature_init}
            }};
            g_thread = CreateThread(NULL, 0, cheat_thread, NULL, 0, NULL);
            break;

        case DLL_PROCESS_DETACH:
            g_running = false;
            if (g_thread) {{
                WaitForSingleObject(g_thread, 1000);
                CloseHandle(g_thread);
            }}
            break;
    }}
    return TRUE;
}}

// ============================================================
//  Export: toggle feature by name
// ============================================================
extern "C" __declspec(dllexport) void toggle_feature(const char* name) {{
    for (auto& f : g_features) {{
        if (strcmp(f.name, name) == 0) {{
            f.toggle = !f.toggle;
            f.enabled = f.toggle;
        }}
    }}
}}

// ============================================================
//  Export: enable/disable all
// ============================================================
extern "C" __declspec(dllexport) void enable_all() {{
    for (auto& f : g_features) {{
        f.enabled = true;
    }}
}}

extern "C" __declspec(dllexport) void disable_all() {{
    for (auto& f : g_features) {{
        f.enabled = false;
    }}
}}

// ============================================================
//  Export: shutdown (for clean unload)
// ============================================================
extern "C" __declspec(dllexport) void deinject() {{
    g_running = false;
}}
"""


# ============================================================
# Type mapping
# ============================================================

TYPE_MAP = {
    "int32": (0, "int32_val"),
    "uint32": (1, "int32_val"),
    "int64": (3, "int64_val"),
    "uint64": (3, "int64_val"),
    "float": (2, "float_val"),
    "double": (4, "double_val"),
    "int16": (0, "int32_val"),
    "uint16": (1, "int32_val"),
    "int8": (0, "int32_val"),
    "uint8": (1, "int32_val"),
}


def _get_type_info(vtype: str) -> tuple:
    """Return (type_code, value_field) for a given type string."""
    vtype = vtype.lower().strip()
    return TYPE_MAP.get(vtype, (0, "int32_val"))


# ============================================================
# DLL Compiler
# ============================================================

class DLLCompiler:
    """Generate and compile injectable DLLs from cheat table entries."""

    def __init__(self, gpp_path: str = "g++"):
        self.gpp_path = gpp_path
        self._last_source = ""
        self._last_log = ""

    def generate_source(self, features: List[Dict], dll_name: str = "MomoTrainer") -> str:
        """Generate C++ source code from feature list.

        features: list of dicts with keys:
            name: str — feature name
            address: int — memory address
            vtype: str — value type (int32, float, etc.)
            value: int/float — value to write
            mode: str — "freeze", "set", or "nudge"
            hotkey: int — VK code (optional)
        """
        configs = []
        feature_inits = []

        for i, f in enumerate(features):
            name = f.get('name', f'Feature_{i}')
            addr = f.get('address', 0)
            vtype = f.get('vtype', 'int32')
            value = f.get('value', 0)
            mode = f.get('mode', 'freeze')
            hotkey = f.get('hotkey', 0)

            type_code, val_field = _get_type_info(vtype)

            # Mode mapping
            mode_map = {'freeze': 0, 'set': 1, 'nudge': 2}
            mode_code = mode_map.get(mode, 0)

            # Nudge amount
            nudge = f.get('nudge', 0)

            # Build the value initialization
            if val_field == "float_val":
                float_val = f"{value}f"
                int32_val = 0
                int64_val = "0LL"
                double_val = "0.0"
            elif val_field == "double_val":
                float_val = "0.0f"
                int32_val = 0
                int64_val = "0LL"
                double_val = str(value)
            elif val_field == "int64_val":
                float_val = "0.0f"
                int32_val = 0
                int64_val = f"{value}LL"
                double_val = "0.0"
            else:
                float_val = "0.0f"
                int32_val = int(value)
                int64_val = "0LL"
                double_val = "0.0"

            feature_inits.append(
                f'            {{"{name}", x{addr:X}, {type_code}, {int32_val}, {int64_val}, {float_val}, {double_val}, {nudge}, {mode_code}, {hotkey}, true, true}}'
            )

        # Escape braces in generated code so .format() doesn't choke
        feature_init_str = ",\n".join(feature_inits) if feature_inits else "{}"
        feature_init_str = feature_init_str.replace("{", "{{").replace("}", "}}")

        source = DLL_TEMPLATE.format(
            dll_name=dll_name,
            timestamp=time.strftime('%Y-%m-%d %H:%M:%S'),
            feature_configs="",
            feature_init=feature_init_str,
        )

        self._last_source = source
        return source

    def save_source(self, source: str, path: str):
        """Save generated source to file."""
        Path(path).write_text(source, encoding='utf-8')

    def compile(self, output_path: str, source_path: Optional[str] = None,
                features: Optional[List[Dict]] = None, dll_name: str = "MomoTrainer",
                source: Optional[str] = None) -> bool:
        """Compile features into a DLL.

        Either provide source_path OR (features + dll_name) OR source directly.
        """
        if source_path:
            src = Path(source_path).read_text(encoding='utf-8')
        elif source:
            src = source
        elif features:
            src = self.generate_source(features, dll_name)
        else:
            self._last_log = "Error: Provide source_path or features"
            return False

        # Write source to temp file
        with tempfile.NamedTemporaryFile(suffix=".cpp", delete=False, mode='w') as f:
            f.write(src)
            src_path = f.name

        try:
            # Compile command
            cmd = [
                self.gpp_path,
                "-shared",           # DLL
                "-o", output_path,   # output path
                src_path,            # source
                "-static-libgcc",    # static link
                "-static-libstdc++", # static link
                "-Wl,--kill-at",     # clean exports
                "-m64",              # 64-bit
            ]

            result = subprocess.run(cmd, capture_output=True, text=True)
            self._last_log = result.stdout + result.stderr

            if result.returncode != 0:
                return False

            return os.path.exists(output_path)
        finally:
            os.unlink(src_path)

    def get_log(self) -> str:
        return self._last_log

    def get_source(self) -> str:
        return self._last_source


