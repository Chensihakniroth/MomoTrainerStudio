# ============================================================
# Helper: convert cheat table entries to DLL features
# ============================================================

def cheat_table_to_features(addresses: list) -> List[Dict]:
    """Convert MomoTrainer cheat table entries to DLL feature format."""
    features = []
    for entry in addresses:
        addr = entry.get('addr', entry.get('address', 0))
        vtype = entry.get('vtype', 'int32')
        desc = entry.get('description', 'Feature')
        frozen = entry.get('frozen', False)
        value = entry.get('value', 0)

        features.append({
            'name': desc,
            'address': addr,
            'vtype': vtype,
            'value': value,
            'mode': 'freeze' if frozen else 'set',
        })

    return features
