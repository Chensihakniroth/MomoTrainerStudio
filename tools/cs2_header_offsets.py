"""Read CS2 offsets from the generated overlay header. Single source of truth.

## Why this exists

`ExternalOverlay/src/cs2_offsets.h` is GENERATED by
`tools/cs2_gen_overlay_header.py` and is already the contract between the two
repos. Twenty-six scripts in this repo ignored it and hardcoded their own
constants instead:

    ENTITY_LIST = 0x2715828     # stale: moved to 0x2715818 on 2026-10-03
    LOCAL_PAWN  = 0x2560698     # still correct

CS2 build 14188 moved two globals by `-0x10` and every one of those scripts
silently read the wrong memory. A stale offset does not raise: it returns a
plausible value or nothing at all, which is the same class of failure as
handoff SS4 (the PAGE_READWRITE bit bug fabricating "0 references").

Fixing the number would just re-arm the same trap at the next patch. So these
scripts read the header instead, and a stale header now produces ONE clear
error naming the fix, instead of 26 scripts quietly lying.

## Usage

    from cs2_offsets import offsets, OffsetsError

    o = offsets()          # cached; raises OffsetsError if the header is stale
    o.ENTITY_LIST          # 0x2715818
    o.HEALTH               # 0x34C
    o.PAGE_OFFSET          # 0x10

Call `offsets(refresh=True)` in a long-lived process that wants to pick up a
regenerated header.

## Staleness check

The header records the build it was generated for. If the installed client's
build differs, that is almost always the reason a probe reports nonsense -
so it is surfaced as an error rather than left for the caller to discover.
"""
import os
import re
import sys

# The generated header. Overridable for tests / alternate checkouts.
HEADER = os.environ.get(
    "CS2_OFFSETS_HEADER",
    r"D:\game\ExternalOverlay\src\cs2_offsets.h")

BUILD_ENV = os.environ.get("CS2_BUILD")      # override to skip the live check


class OffsetsError(RuntimeError):
    pass


class Offsets:
    """Attribute access over the generated header."""

    def __init__(self, values, build, path):
        self._v = values
        self.build = build
        self.path = path

    def __getattr__(self, name):
        try:
            return self._v[name]
        except KeyError:
            raise AttributeError(
                f"{name!r} is not in {self.path}. Known keys: "
                + ", ".join(sorted(self._v))) from None

    def __getitem__(self, name):
        return self._v[name]

    def __contains__(self, name):
        return name in self._v

    def as_dict(self):
        return dict(self._v)


# kEntityList -> ENTITY_LIST
def _norm(k):
    return re.sub(r'^k', '', k).upper()

# Header constant -> the legacy name the scripts already use, so the sweep
# keeps each script's existing identifier and its existing comments.
ALIASES = {
    "ENTITYLIST": "ENTITY_LIST",
    "ENTITY_LIST": "ENTITY_LIST",
    "LOCALPLAYERPAWN": "LOCAL_PAWN",
    "LOCAL_PLAYER_PAWN": "LOCAL_PAWN",
    "LOCALPLAYERCONTROLLER": "LOCAL_CONTROLLER",
    "LOCAL_PLAYER_CONTROLLER": "LOCAL_CONTROLLER",
    "GAMEENTITYSYSTEM": "ENTITY_SYSTEM",
    "HIGHESTENTITYINDEX": "HIGHEST_ENTITY_INDEX",
    "VIEWANGLES": "VIEW_ANGLES",
    "VIEWMATRIX": "VIEW_MATRIX",
    "GLOBALVARS": "GLOBAL_VARS",
    "PAGEOFFSET": "PAGE_OFFSET",
    "SLOTSTRIDE": "SLOT_STRIDE",
    "HANDLEMASK": "HANDLE_MASK",
    "MAXSLOTS": "MAX_SLOTS",
    "CONTROLLERCOUNT": "CONTROLLER_COUNT",
    "OFFHEALTH": "HEALTH",
    "OFFHEALTHVIDEO": "HEALTH_VIDEO",
    "OFFTEAMNUM": "TEAM_NUM",
    "OFFGAMESCENENODE": "SCENE_NODE",
    "OFFABSORIGIN": "ABS_ORIGIN",
    "OFFPLAYERPAWN": "PLAYER_PAWN",
    "OFFPLAYERPAWNVIDEO": "PLAYER_PAWN_VIDEO",
    "OFFPLAYERNAME": "PLAYER_NAME",
    "OFFPLAYERNAMEVIDEO": "PLAYER_NAME_VIDEO",
    "OFFISLOCALCONTROLLER": "IS_LOCAL_CONTROLLER",
    "OFFARMOR": "ARMOR",
    "OFFBOUNDMIN": "BOUNDS_MIN",
    "OFFBOUNDMAX": "BOUNDS_MAX",
    "OFFVIEWOFFSET": "VIEW_OFFSET",
    "OFFHEALTHREGEN": "HEALTH_REGEN",
}

_CONST = re.compile(
    r'^\s*constexpr\s+(?:u?int\d+_t|int|float|uint32_t)\s+(\w+)\s*=\s*'
    r'(0[xX][0-9a-fA-F]+|\d+)\s*;', re.M)


def _parse(path):
    if not os.path.exists(path):
        raise OffsetsError(
            f"offsets header not found: {path}\n"
            f"Generate it with:\n"
            f"  python D:\\game\\MomoTrainerStudio\\tools\\cs2_gen_overlay_header.py\n"
            f"or point CS2_OFFSETS_HEADER at the real file.")
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()

    build = None
    m = re.search(r'kBuildNumber\s*=\s*(\d+)', text)
    if m:
        build = int(m.group(1))

    values = {}
    for name, raw in _CONST.findall(text):
        key = ALIASES.get(_norm(name).replace("_", ""), None)
        if key is None:
            key = ALIASES.get(_norm(name), _norm(name))
        # first definition wins, mirroring the header's own ordering
        values.setdefault(key, int(raw, 0))
    if not values:
        raise OffsetsError(f"no constants parsed from {path}")
    return values, build


def _installed_build():
    """Build number of the installed CS2, or None if it cannot be read."""
    if BUILD_ENV:
        try:
            return int(BUILD_ENV)
        except ValueError:
            return None
    # Steam appmanifest: 730 is CS2
    for appid in ("730",):
        mf = (rf"C:\Program Files (x86)\Steam\steamapps\appmanifest_{appid}.acf"
              r"D:\SteamLibrary\steamapps\appmanifest_730.acf"
              r"C:\Program Files\Steam\steamapps\appmanifest_730.acf")
        if not os.path.exists(mf):
            continue
        with open(mf, encoding="utf-8", errors="replace") as f:
            m = re.search(r'"buildid"\s+"(\d+)"', f.read())
        if m:
            return int(m.group(1))
    return None


_cache = None


def offsets(refresh=False):
    global _cache
    if _cache is not None and not refresh:
        return _cache
    values, build = _parse(HEADER)
    o = Offsets(values, build, HEADER)
    _cache = o
    return o


def check_build(warn_only=False):
    """Compare the header's build against the installed client.

    Returns (ok, message). Called by the sweep so a stale header is reported
    once, loudly, instead of being rediscovered as 'the tool is broken'.
    """
    o = offsets()
    live = _installed_build()
    if live is None or o.build is None:
        return True, "installed build unknown - skipped"
    if live != o.build:
        msg = (f"CS2 build mismatch: header={o.build} installed={live}\n"
               f"  Re-run: python tools\\cs2_gen_overlay_header.py\n"
               f"  Every probe below will read wrong memory until you do.")
        if warn_only:
            return False, msg
        raise OffsetsError(msg)
    return True, f"build {o.build} matches the installed client"


def main():
    try:
        ok, msg = check_build(warn_only=True)
    except OffsetsError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    o = offsets()
    print(f"header: {HEADER}")
    print(f"build:  {o.build}   ({msg})")
    print(f"{len(o.as_dict())} constants:\n")
    for k in sorted(o.as_dict()):
        print(f"   {k:<22} 0x{o[k]:08X}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())